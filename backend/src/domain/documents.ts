/** Upload rules. Pure functions: nothing here touches the disk or the database. */
export const DOCUMENT_ENTITIES = ['supplier', 'quotation', 'requisition', 'purchase_order', 'goods_receipt', 'invoice'] as const;
export type DocumentEntity = (typeof DOCUMENT_ENTITIES)[number];

export type DocKind = 'pdf' | 'png' | 'jpg' | 'docx' | 'xlsx' | 'csv' | 'txt';
export const KIND_INFO: Record<DocKind, { mime: string; ext: string }> = {
  pdf: { mime: 'application/pdf', ext: 'pdf' }, png: { mime: 'image/png', ext: 'png' }, jpg: { mime: 'image/jpeg', ext: 'jpg' },
  docx: { mime: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', ext: 'docx' },
  xlsx: { mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', ext: 'xlsx' },
  csv: { mime: 'text/csv', ext: 'csv' }, txt: { mime: 'text/plain', ext: 'txt' },
};
export const DEFAULT_MAX_BYTES = 10 * 1024 * 1024;

const EXT_TO_KIND: Record<string, DocKind> = { pdf: 'pdf', png: 'png', jpg: 'jpg', jpeg: 'jpg', docx: 'docx', xlsx: 'xlsx', csv: 'csv', txt: 'txt' };
export const extensionOf = (name: string) => (name.toLowerCase().match(/\.([a-z0-9]{1,5})$/)?.[1] ?? '');

/** The real type, from the file's own first bytes. The browser's declared type and the file extension are never trusted alone. */
export function sniff(buf: Buffer): DocKind | 'zip' | 'text' | null {
  if (buf.length < 4) return null;
  if (buf.subarray(0, 5).toString('latin1') === '%PDF-') return 'pdf';
  if (buf[0] === 0x89 && buf.subarray(1, 4).toString('latin1') === 'PNG') return 'png';
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'jpg';
  if (buf[0] === 0x50 && buf[1] === 0x4b && (buf[2] === 0x03 || buf[2] === 0x05) ) return 'zip'; // docx/xlsx are zip containers
  const head = buf.subarray(0, Math.min(buf.length, 8192));
  if (!head.includes(0)) { try { new TextDecoder('utf-8', { fatal: true }).decode(head.subarray(0, head.length - 3)); return 'text'; } catch { return null; } }
  return null;
}

export type Verdict = { ok: true; kind: DocKind; mime: string; ext: string } | { ok: false; reason: string };

/** Accept only when extension, content and size all agree on an allowed type. */
export function validateUpload(file: { originalName: string; size: number; buffer: Buffer }, maxBytes = DEFAULT_MAX_BYTES): Verdict {
  if (file.size === 0) return { ok: false, reason: 'The file is empty' };
  if (file.size > maxBytes) return { ok: false, reason: `The file is larger than the ${Math.round(maxBytes / 1024 / 1024)} MB limit` };
  const ext = extensionOf(file.originalName);
  const claimed = EXT_TO_KIND[ext];
  if (!claimed) return { ok: false, reason: 'This file type is not allowed. Allowed: PDF, PNG, JPG, DOCX, XLSX, CSV, TXT' };
  const found = sniff(file.buffer);
  const consistent =
    (claimed === 'pdf' && found === 'pdf') || (claimed === 'png' && found === 'png') || (claimed === 'jpg' && found === 'jpg') ||
    ((claimed === 'docx' || claimed === 'xlsx') && found === 'zip') || ((claimed === 'csv' || claimed === 'txt') && found === 'text');
  if (!consistent) return { ok: false, reason: 'The file content does not match its extension' };
  if (claimed === 'docx' || claimed === 'xlsx') {
    // Office files are zips; a bare zip renamed to .docx has no [Content_Types].xml entry.
    if (!file.buffer.includes(Buffer.from('[Content_Types].xml'))) return { ok: false, reason: 'The file is not a valid Office document' };
  }
  const info = KIND_INFO[claimed];
  return { ok: true, kind: claimed, mime: info.mime, ext: info.ext };
}

/** Display name only (never used as a path): no directories, no control characters, bounded length. */
export function displayName(original: string): string {
  const base = original.replace(/\\/g, '/').split('/').pop() ?? '';
  const clean = base.replace(/[\u0000-\u001f\u007f<>:"|?*]/g, '').replace(/\s+/g, ' ').trim();
  return (clean || 'document').slice(0, 120);
}

/** Storage keys are generated by the server from an id and the DETECTED extension, so a user can never choose a path. */
export const KEY_PATTERN = /^[a-z_]{4,16}\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(pdf|png|jpg|docx|xlsx|csv|txt)$/;
export const makeKey = (entity: DocumentEntity, uuid: string, ext: string) => `${entity}/${uuid}.${ext}`;
